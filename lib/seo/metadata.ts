// Metadata builders (docs/SEO.md §5, docs/CONTRACTS.md §3). Owned by seo-content.
// Titles in content are complete ("… | Img Master"), so nothing here adds the
// brand again. Every page sets its own full openGraph and twitter objects,
// because Next.js merges these fields shallowly between segments.
import type { Metadata } from 'next';
import { homeContent } from '@/content/home';
import { siteConfig } from '@/lib/site-config';
import type { ToolContent, ToolDefinition } from '@/lib/types';
import { absoluteUrl, siteOrigin } from './url';

export { absoluteUrl, siteOrigin, toPlainText } from './url';

const INDEX: Metadata['robots'] = { index: true, follow: true };
const NOINDEX: Metadata['robots'] = { index: false, follow: true };

/** Root layout metadata: base URL, default title, site name, base OG/Twitter. */
export function buildRootMetadata(): Metadata {
  return {
    metadataBase: new URL(siteOrigin()),
    title: { default: homeContent.title, template: '%s' },
    description: homeContent.description,
    applicationName: siteConfig.name,
    authors: [{ name: siteConfig.owner.company, url: siteConfig.owner.companyUrl }],
    creator: siteConfig.owner.company,
    publisher: siteConfig.owner.company,
    formatDetection: { telephone: false, email: false, address: false },
    robots: INDEX,
    openGraph: {
      type: 'website',
      siteName: siteConfig.name,
      locale: 'en_US',
      title: homeContent.title,
      description: homeContent.description,
      url: absoluteUrl('/'),
    },
    twitter: {
      card: 'summary_large_image',
      title: homeContent.title,
      description: homeContent.description,
    },
  };
}

interface PageMetaInput {
  title: string;
  description: string;
  path: string;
  noindex?: boolean;
}

/**
 * Home, legal and other site pages. Pass the complete title.
 * The Open Graph image comes from the opengraph-image file convention
 * (app/opengraph-image.tsx), which Next.js adds on top of this object.
 */
export function buildPageMetadata(p: PageMetaInput): Metadata {
  const url = absoluteUrl(p.path);
  return {
    title: { absolute: p.title },
    description: p.description,
    alternates: p.noindex ? undefined : { canonical: url },
    robots: p.noindex ? NOINDEX : INDEX,
    openGraph: {
      type: 'website',
      siteName: siteConfig.name,
      locale: 'en_US',
      title: p.title,
      description: p.description,
      url,
    },
    twitter: {
      card: 'summary_large_image',
      title: p.title,
      description: p.description,
    },
  };
}

/**
 * Tool pages. The page-specific Open Graph image is generated by
 * app/[slug]/opengraph-image.tsx; the static category image in public/og/ is
 * the fallback for platforms that only read twitter:image.
 */
export function buildToolMetadata(tool: ToolDefinition, content: ToolContent): Metadata {
  return buildPageMetadata({
    title: content.title,
    description: content.description,
    path: `/${tool.slug}`,
  });
}
